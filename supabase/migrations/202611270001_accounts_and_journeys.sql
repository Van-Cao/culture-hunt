-- Application tables are private to the Next.js server. Supabase Auth owns credentials.
CREATE SCHEMA IF NOT EXISTS culture_hunt;
REVOKE ALL ON SCHEMA culture_hunt FROM PUBLIC, anon, authenticated;
CREATE TABLE IF NOT EXISTS culture_hunt.schema_migrations(version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS culture_hunt.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name TEXT NOT NULL CHECK(length(display_name) BETWEEN 1 AND 80), updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS culture_hunt.runs (
  id TEXT PRIMARY KEY, owner TEXT NOT NULL, started_at TEXT NOT NULL, completed_at TEXT,
  status TEXT NOT NULL CHECK(status IN ('active','completed','abandoned')),
  _order BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX IF NOT EXISTS runs_owner ON culture_hunt.runs(owner);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_run ON culture_hunt.runs(owner) WHERE status='active';
CREATE TABLE IF NOT EXISTS culture_hunt.visits (
  run_id TEXT NOT NULL REFERENCES culture_hunt.runs(id), checkpoint_id TEXT NOT NULL,
  recognized_at TEXT NOT NULL, mode TEXT NOT NULL, completed_at TEXT, quiz_json TEXT, challenge_json TEXT,
  PRIMARY KEY(run_id,checkpoint_id)
);
CREATE TABLE IF NOT EXISTS culture_hunt.attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id TEXT NOT NULL REFERENCES culture_hunt.runs(id),
  checkpoint_id TEXT NOT NULL, at TEXT NOT NULL, answer INTEGER NOT NULL, correct INTEGER NOT NULL CHECK(correct IN (0,1)),
  question_id TEXT, answer_json TEXT
);
CREATE INDEX IF NOT EXISTS attempts_run ON culture_hunt.attempts(run_id,checkpoint_id);
CREATE TABLE IF NOT EXISTS culture_hunt.awards (
  owner TEXT NOT NULL, checkpoint_id TEXT NOT NULL, awarded_at TEXT NOT NULL,
  _order BIGINT GENERATED BY DEFAULT AS IDENTITY, PRIMARY KEY(owner,checkpoint_id)
);
CREATE TABLE IF NOT EXISTS culture_hunt.recognitions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id TEXT NOT NULL REFERENCES culture_hunt.runs(id),
  checkpoint_id TEXT NOT NULL, at TEXT NOT NULL, mode TEXT NOT NULL, result TEXT NOT NULL, candidate TEXT
);
CREATE TABLE IF NOT EXISTS culture_hunt.game_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id TEXT NOT NULL REFERENCES culture_hunt.runs(id),
  checkpoint_id TEXT NOT NULL, at TEXT NOT NULL, move_json TEXT NOT NULL, accepted INTEGER NOT NULL, solved INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS culture_hunt.explorer_progress (
  owner TEXT PRIMARY KEY, hcmus INTEGER NOT NULL DEFAULT 0 CHECK(hcmus BETWEEN 0 AND 4),
  saved_json TEXT NOT NULL DEFAULT '[]', updated_at TEXT NOT NULL
);
ALTER TABLE culture_hunt.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE culture_hunt.runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE culture_hunt.visits ENABLE ROW LEVEL SECURITY;
ALTER TABLE culture_hunt.attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE culture_hunt.awards ENABLE ROW LEVEL SECURITY;
ALTER TABLE culture_hunt.recognitions ENABLE ROW LEVEL SECURITY;
ALTER TABLE culture_hunt.game_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE culture_hunt.explorer_progress ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA culture_hunt FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA culture_hunt FROM PUBLIC, anon, authenticated;
