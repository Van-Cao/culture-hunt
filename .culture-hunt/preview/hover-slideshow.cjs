const { chromium } = require('C:/Users/Admin/AppData/Local/npm-cache/_npx/420ff84f11983ee5/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser=await chromium.launch({headless:true,executablePath:'C:/Users/Admin/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe'});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.clock.install();
 await page.goto('http://localhost:3000/?lang=en',{waitUntil:'networkidle'});
 assert.equal(await page.locator('.travel-zoom').count(),0);
 await page.mouse.move(100,200); await page.waitForTimeout(900);
 const left=await page.locator('.travel-hero-scene').evaluate(e=>({origin:getComputedStyle(e).transformOrigin,scale:new DOMMatrix(getComputedStyle(e).transform).a}));
 assert.ok(left.scale>1.15);
 await page.mouse.move(1300,600); await page.waitForTimeout(900);
 const right=await page.locator('.travel-hero-scene').evaluate(e=>getComputedStyle(e).transformOrigin);
 assert.ok(parseFloat(right)>parseFloat(left.origin)+800);
 await page.mouse.move(-20,-20); await page.waitForTimeout(900);
 assert.ok(await page.locator('.travel-hero-scene').evaluate(e=>new DOMMatrix(getComputedStyle(e).transform).a<1.01));
 const first=await page.locator('.travel-hero-photo.is-active img').getAttribute('alt');
 await page.clock.fastForward(10000);
 const second=await page.locator('.travel-hero-photo.is-active img').getAttribute('alt');
 assert.notEqual(first,second);
 await page.clock.fastForward(10000);
 assert.equal(await page.locator('.travel-hero-photo.is-active img').getAttribute('alt'),first);
 await page.getByRole('button',{name:'Pause background slideshow'}).click();
 await page.clock.fastForward(20000);
 assert.equal(await page.locator('.travel-hero-photo.is-active img').getAttribute('alt'),first);
 await page.getByRole('button',{name:'Resume background slideshow'}).click();
 await page.clock.fastForward(10000);
 assert.equal(await page.locator('.travel-hero-photo.is-active img').getAttribute('alt'),second);
 await page.getByRole('button',{name:'Get started',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('dialog').getByRole('button',{name:/guest/i}).click();
 await page.waitForURL(/play=1/);
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await mobile.goto('http://localhost:3000/?lang=vi',{waitUntil:'networkidle'});
 await mobile.locator('.travel-eyebrow').tap();
 assert.equal(await mobile.locator('.travel-hero-scene').evaluate(e=>getComputedStyle(e).transform),'none');
 assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.goto('http://localhost:3000/?lang=en',{waitUntil:'networkidle'});
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.mouse.move(600,300); await page.waitForTimeout(500);
 assert.equal(await page.locator('.travel-hero-scene').evaluate(e=>getComputedStyle(e).transform),'none');
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: cursor-targeted zoom and reset, 10-second rotation and wrap, pause/resume, guest entry, touch layout, reduced motion; no runtime errors');
})().catch(e=>{console.error(e);process.exit(1)});
